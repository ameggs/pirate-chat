@app.route("/send", methods=["POST"])
def send_message():
    data = request.get_json()
    if not data:
        return jsonify({"error": "Invalid JSON"}), 400
    username = data.get("username", "").strip()
    message = data.get("message", "").strip()
    if not username:
        return jsonify({"error": "Username is required"}), 400
    if not message:
        return jsonify({"error": "Message is required"}), 400
    conn = get_db()
    conn.execute(
        "INSERT INTO messages (username, message, timestamp) VALUES (?, ?, ?)",
        (username, message, time.time()),
    )
    conn.commit()
    conn.close()
    return jsonify({"status": "ok"}), 201


@app.route("/upload", methods=["POST"])
def upload_image():
    username = request.form.get("username", "").strip()
    if not username:
        return jsonify({"error": "Username is required"}), 400
    if "image" not in request.files:
        return jsonify({"error": "No image file provided"}), 400
    file = request.files["image"]
    if file.filename == "" or not allowed_file(file.filename):
        return jsonify({"error": "Invalid or missing file"}), 400
    ts = str(int(time.time()))
    filename = secure_filename(ts + "_" + file.filename)
    filepath = os.path.join(app.config["UPLOAD_FOLDER"], filename)
    file.save(filepath)
    message = request.form.get("message", "").strip()
    conn = get_db()
    conn.execute(
        "INSERT INTO messages (username, message, image_path, timestamp) VALUES (?, ?, ?, ?)",
        (username, message, filename, time.time()),
    )
    conn.commit()
    conn.close()
    return jsonify({"status": "ok", "filename": filename}), 201


@app.route("/messages")
def get_messages():
    conn = get_db()
    rows = conn.execute(
        "SELECT id, username, message, image_path, timestamp FROM messages ORDER BY id DESC LIMIT 50"
    ).fetchall()
    conn.close()
    messages = []
    for row in reversed(rows):
        msg = {
            "id": row["id"],
            "username": row["username"],
            "message": row["message"],
            "timestamp": row["timestamp"],
        }
        msg["image_url"] = "/uploads/" + row["image_path"] if row["image_path"] else None
        messages.append(msg)
    return jsonify(messages)



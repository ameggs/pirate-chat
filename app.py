@app.route("/upload-file", methods=["POST"])
def upload_file():
    username = request.form.get("username", "anonymous").strip()
    if "file" not in request.files:
        return jsonify({"error": "No file provided"}), 400
    file = request.files["file"]
    if file.filename == "":
        return jsonify({"error": "No file selected"}), 400
    original_name = file.filename
    ts = str(int(time.time()))
    filename = secure_filename(ts + "_" + original_name)
    filepath = os.path.join(app.config["SHARED_FOLDER"], filename)
    file.save(filepath)
    size = os.path.getsize(filepath)
    file_type = mimetypes.guess_type(original_name)[0] or "application/octet-stream"
    conn = get_db()
    conn.execute(
        "INSERT INTO shared_files (filename, original_name, size, file_type, uploaded_at, uploaded_by) "
        "VALUES (?, ?, ?, ?, ?, ?)",
        (filename, original_name, size, file_type, str(time.time()), username),
    )
    conn.commit()
    conn.close()
    return jsonify({"status": "ok", "filename": filename}), 201


@app.route("/download/<filename>")
def download_file(filename):
    safe_name = secure_filename(filename)
    filepath = os.path.join(app.config["SHARED_FOLDER"], safe_name)
    if not os.path.exists(filepath):
        abort(404)
    return send_from_directory(
        app.config["SHARED_FOLDER"],
        safe_name,
        as_attachment=True,
    )



@app.route("/api/stats")
def api_stats():
    conn = get_db()
    # Active users: distinct usernames with messages in last 5 minutes
    cutoff = time.time() - 300
    user_row = conn.execute(
        "SELECT COUNT(DISTINCT username) AS cnt FROM messages WHERE timestamp >= ?",
        (cutoff,),
    ).fetchone()
    active_users = user_row["cnt"] if user_row else 0

    total_row = conn.execute("SELECT COUNT(*) AS cnt FROM messages").fetchone()
    total_messages = total_row["cnt"] if total_row else 0

    files_row = conn.execute("SELECT COUNT(*) AS cnt FROM shared_files").fetchone()
    total_files = files_row["cnt"] if files_row else 0

    conn.close()
    return jsonify(
        {
            "users": active_users,
            "messages_total": total_messages,
            "files_total": total_files,
        }
    )


